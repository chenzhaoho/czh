//=====================================================================
// syn_wrap_single.v -- synthesis/implementation wrapper (PPA analysis only)
//
// Why this wrapper exists:
//   fifo_a exposes every statistic/debug output on its ports
//   (hundreds of pins). xc7a35tcsg324 only has 210 user I/O, so
//   place_design fails with IO overutilization. On a real chip those
//   counters feed internal registers/buses, not package pins.
//
// This wrapper keeps only the real datapath ports and sinks the
// debug bus into a keep-register, so synthesis cannot optimise the
// statistic logic away -- area/timing still reflect the full design.
//
// GENERATED by syn/gen_wrappers.py -- do not edit by hand.
//=====================================================================
module syn_wrap_single (
    input  wire rst_n_async,
    output wire [7:0] dbg_sig,
    input  wire wr_clk,
    input  wire wr_valid,
    input  wire [31:0] wr_data,
    output wire wr_ready,
    output wire wr_full,
    output wire wr_almost_full,
    input  wire rd_clk,
    input  wire rd_en,
    input  wire rd_ready,
    output wire [31:0] rd_data,
    output wire rd_valid,
    output wire rd_empty,
    output wire rd_almost_empty,
    input  wire clk_mon
);

    //-------------------- internal observation nets --------------------
    wire full_check;
    wire [31:0] wr_data_committed;
    wire wr_data_valid;
    wire [31:0] wr_event_cnt;
    wire [31:0] overflow_cnt;
    wire [31:0] overflow_flag_cnt;
    wire [8:0] wr_used_dbg;
    wire [31:0] rd_event_cnt;
    wire [31:0] underflow_cnt;
    wire [31:0] underflow_flag_cnt;
    wire [31:0] backpressure_cnt;
    wire backpressure_active;
    wire [8:0] rd_used_dbg;
    wire [31:0] wr_event_cnt_sync;
    wire [31:0] rd_event_cnt_sync;
    wire [31:0] overflow_cnt_sync;
    wire [31:0] underflow_cnt_sync;
    wire [31:0] backpressure_cnt_sync;
    wire [8:0] used_sync;
    wire full_sync;
    wire almost_full_sync;
    wire empty_sync;
    wire almost_empty_sync;

    // 监控域复位: 与原设计一致, 异步置位 + 同步释放
    wire rst_n_mon_sync;
    rst_sync #(.STAGES(2)) u_rst_sync_mon (
        .clk(clk_mon), .rst_n_async(rst_n_async), .rst_n_sync(rst_n_mon_sync));

    fifo_a u_fifo_a (
        .rst_n_async                (rst_n_async),
        .wr_clk                     (wr_clk),
        .wr_valid                   (wr_valid),
        .wr_data                    (wr_data),
        .wr_ready                   (wr_ready),
        .wr_full                    (wr_full),
        .full_check                 (full_check),
        .wr_almost_full             (wr_almost_full),
        .wr_data_committed          (wr_data_committed),
        .wr_data_valid              (wr_data_valid),
        .wr_event_cnt               (wr_event_cnt),
        .overflow_cnt               (overflow_cnt),
        .overflow_flag_cnt          (overflow_flag_cnt),
        .wr_used_dbg                (wr_used_dbg),
        .rd_clk                     (rd_clk),
        .rd_en                      (rd_en),
        .rd_ready                   (rd_ready),
        .rd_data                    (rd_data),
        .rd_valid                   (rd_valid),
        .rd_empty                   (rd_empty),
        .rd_almost_empty            (rd_almost_empty),
        .rd_event_cnt               (rd_event_cnt),
        .underflow_cnt              (underflow_cnt),
        .underflow_flag_cnt         (underflow_flag_cnt),
        .backpressure_cnt           (backpressure_cnt),
        .backpressure_active        (backpressure_active),
        .rd_used_dbg                (rd_used_dbg),
        .clk_mon                    (clk_mon),
        .rst_n_mon                  (rst_n_mon_sync),
        .wr_event_cnt_sync          (wr_event_cnt_sync),
        .rd_event_cnt_sync          (rd_event_cnt_sync),
        .overflow_cnt_sync          (overflow_cnt_sync),
        .underflow_cnt_sync         (underflow_cnt_sync),
        .backpressure_cnt_sync      (backpressure_cnt_sync),
        .used_sync                  (used_sync),
        .full_sync                  (full_sync),
        .almost_full_sync           (almost_full_sync),
        .empty_sync                 (empty_sync),
        .almost_empty_sync          (almost_empty_sync)
    );

    //-------------------- observation checksum --------------------
    // Every statistic participates in a reduction-XOR so synthesis cannot
    // drop the observing logic. 8 bits are exported for inspection.
    reg [7:0] dbg_sig_r;
    always @(posedge clk_mon or negedge rst_n_async) begin
        if (!rst_n_async) begin
            dbg_sig_r <= 8'd0;
        end else begin
            dbg_sig_r <= {
                ^{full_check, underflow_cnt, underflow_cnt_sync},
                ^{wr_data_committed, underflow_flag_cnt, backpressure_cnt_sync},
                ^{wr_data_valid, backpressure_cnt, used_sync},
                ^{wr_event_cnt, backpressure_active, full_sync},
                ^{overflow_cnt, rd_used_dbg, almost_full_sync},
                ^{overflow_flag_cnt, wr_event_cnt_sync, empty_sync},
                ^{wr_used_dbg, rd_event_cnt_sync, almost_empty_sync},
                ^{rd_event_cnt, overflow_cnt_sync}
            };
        end
    end
    assign dbg_sig = dbg_sig_r;

endmodule
